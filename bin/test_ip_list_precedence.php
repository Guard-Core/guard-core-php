<?php

declare(strict_types=1);

use RenzoFranceschini\GuardCore\Config\SecurityConfig;
use RenzoFranceschini\GuardCore\Engine\GuardEngine;
use RenzoFranceschini\GuardCore\Request\SimpleGuardRequest;
use RenzoFranceschini\GuardCore\Routing\RouteConfig;

require __DIR__ . '/../vendor/autoload.php';

// IP list precedence parity with the reference engine (guard-core Python,
// _utils/access_control.py _check_ip_lists_detail and
// core/checks/helpers.py check_route_ip_access): a configured whitelist
// decides alone and the blacklist is consulted only when no whitelist is
// configured. tests/data/ip_list_precedence.json is generated by running the
// reference over every row, never hand-written. In-memory, no Redis.

$passed = 0;
$failed = 0;

$rows = json_decode((string) file_get_contents(__DIR__ . '/../tests/data/ip_list_precedence.json'), true, flags: JSON_THROW_ON_ERROR);

foreach ($rows as $row) {
    if ($row['ip'] === 'unknown') {
        continue;
    }
    $label = 'wl=' . json_encode($row['whitelist']) . ' bl=' . json_encode($row['blacklist']) . ' ip=' . $row['ip'];

    $engine = new GuardEngine(new SecurityConfig(
        enableRedis: false,
        whitelist: $row['whitelist'] === [] ? null : $row['whitelist'],
        blacklist: $row['blacklist'],
    ));
    $status = $engine->execute(new SimpleGuardRequest(urlPath: '/', clientHost: $row['ip']))?->statusCode();
    $expected = $row['global'] ? null : 403;
    if ($status === $expected) {
        $passed++;
    } else {
        $failed++;
        echo "FAIL global {$label}: expected " . var_export($expected, true) . ', got ' . var_export($status, true) . "\n";
    }

    $engine = new GuardEngine(new SecurityConfig(enableRedis: false));
    $request = new SimpleGuardRequest(urlPath: '/', clientHost: $row['ip']);
    $request->state()->routeConfig = new RouteConfig(ipWhitelist: $row['whitelist'], ipBlacklist: $row['blacklist']);
    $status = $engine->execute($request)?->statusCode();
    $expected = $row['route'] === false ? 403 : null;
    if ($status === $expected) {
        $passed++;
    } else {
        $failed++;
        echo "FAIL route {$label}: expected " . var_export($expected, true) . ', got ' . var_export($status, true) . "\n";
    }
}

echo "\ntest_ip_list_precedence: {$passed} passed, {$failed} failed\n";
exit($failed === 0 ? 0 : 1);
